const f = (
  level: number,
  name: string,
  description: string,
  extra: Partial<SubclassFeature> = {},
): SubclassFeature => ({ level, name, description, ...extra });
const make = (
  edition: Edition,
  id: string,
  name: string,
  features: SubclassFeature[],
  extra: Partial<SubclassExtension> = {},
): SubclassExtension => ({
  id,
  classId: "ranger",
  name,
  description: `Архетип следопыта редакции ${edition}.`,
  editions: [edition],
  level2014: 3,
  source:
    edition === "2014"
      ? "Xanathar’s Guide to Everything"
      : "Player’s Handbook (2024)",
  sourceUrl:
    edition === "2014"
      ? `https://dnd.su/class/97-ranger/#archetype.${id}`
      : `https://next.dnd.su/class/ranger#subclass.${id}`,
  features,
  ...extra,
});
const grants = (...ids: string[]): [number, string[]][] =>
  ids.map((id, i) => [[3, 5, 9, 13, 17][i], [id]]);
