export function subclassExtension(
  classId: string,
  id: string | undefined,
  edition: Edition,
) {
  const selected = SUBCLASS_EXTENSIONS.find(
    (s) => s.classId === classId && s.id === id && s.editions.includes(edition),
  );
  if (classId !== "artificer") return selected;
  const base = ARTIFICER_BASE_RULES[edition];
  return {
    ...base, ...selected,
    features: [...base.features.map(f => ({...f, source:base.source, sourceUrl:base.sourceUrl})), ...(selected?.features ?? [])],
    choices: [...(base.choices ?? []), ...(selected?.choices ?? [])],
    choicePools: [...(base.choicePools ?? []), ...(selected?.choicePools ?? [])],
    grants: [...(base.grants ?? []), ...(selected?.grants ?? [])],
  };
}
