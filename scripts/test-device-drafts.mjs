import { build } from "esbuild";
import assert from "node:assert/strict";
const result=await build({entryPoints:["apps/web/src/app/device-drafts.ts"],bundle:true,write:false,format:"esm",platform:"node"});
const {writeDeviceDraft,readDeviceDrafts,removeDeviceDrafts}=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`);
const records=new Map();let failWrites=false;
globalThis.window={localStorage:{get length(){return records.size},key:i=>[...records.keys()][i]??null,getItem:key=>records.get(key)??null,setItem:(key,value)=>{if(failWrites)throw new DOMException("Full","QuotaExceededError");records.set(key,value)},removeItem:key=>records.delete(key)}};
const draft=(text,revision=3)=>({version:2,baseRevision:revision,savedAt:"2026-10-23T16:00:00Z",value:{text}});
const a=writeDeviceDraft("alice","campaign","entity:one","tab-a",draft("A"));
const b=writeDeviceDraft("alice","campaign","entity:one","tab-b",draft("B"));
writeDeviceDraft("alice","campaign","entity:one","tab-a",draft("A changed"));
assert.notEqual(a,b);
assert.deepEqual(new Set(readDeviceDrafts("alice","campaign","entity:one").map(d=>d.value.text)),new Set(["A changed","B"]));
const rebased=writeDeviceDraft("alice","campaign","entity:one","tab-a",draft("A on new server version",4));
assert.equal(readDeviceDrafts("alice","campaign","entity:one").length,3,"stale-base copy stays recoverable");
assert.equal(readDeviceDrafts("bob","campaign","entity:one").length,0);
assert.equal(readDeviceDrafts("alice","other-campaign","entity:one").length,0);
assert.equal(readDeviceDrafts("alice","campaign","entity:two").length,0);
const unknownBase=writeDeviceDraft("alice","campaign","legacy:event","tab-a",draft("legacy version needs comparison",-1));
assert.equal(readDeviceDrafts("alice","campaign","legacy:event")[0].baseRevision,-1,"unknown legacy base must remain recoverable and require a server conflict");
removeDeviceDrafts([unknownBase]);
const legacy=`shadow-edge.draft.v1:${JSON.stringify(["alice","campaign","entity:one"])}`;
records.set(legacy,JSON.stringify({...draft("old format"),version:1}));
assert.equal(readDeviceDrafts("alice","campaign","entity:one").length,4,"legacy retained without destructive migration");
removeDeviceDrafts([a,rebased]);
assert.deepEqual(new Set(readDeviceDrafts("alice","campaign","entity:one").map(d=>d.value.text)),new Set(["B","old format"]));
failWrites=true;
assert.equal(writeDeviceDraft("alice","campaign","entity:one","tab-c",draft("quota failure")),null);
assert.equal(readDeviceDrafts("alice","campaign","entity:one").length,3,"failed write preserves existing copies and retains the new one in memory");
assert.equal(readDeviceDrafts("alice","campaign","entity:one").find(d=>d.value.text==="quota failure").memoryOnly,true);
records.set("shadow-edge.draft.v2:[\"alice\",\"campaign\",\"entity:one\"]:corrupt","{invalid");
assert.equal(readDeviceDrafts("alice","campaign","entity:one").length,3);
assert.equal(records.get("shadow-edge.draft.v2:[\"alice\",\"campaign\",\"entity:one\"]:corrupt"),"{invalid");
console.log("Passed: independent tab copies, base revisions, owner/campaign/target isolation, legacy recovery, scoped cleanup, quota and corrupt-source preservation.");
